function Write (texts: any[]) {
    string_number = 0
    myTextSprite = fancyText.create("", 150, 1, fancyText.geometric_serif_6)
    myTextSprite.setPosition(80, 22)
    for (let index = 0; index < texts.length; index++) {
        fancyText.setText(myTextSprite, texts[string_number])
        fancyText.animateAtSpeed(myTextSprite, fancyText.TextSpeed.Fast, fancyText.AnimationPlayMode.UntilDone)
        pause(500)
        string_number += 1
    }
}
